const IS_WIN = process.platform === "win32";

function pickJob(p?: string): { job: ScanJob; abs: string } | ToolResult {
  if (p) {
    const abs = resolveInput(p);
    const job = registry.findDone(abs);
    return job ? { job, abs } : noScanMessage(abs);
  }
  const job = registry.latestDone();
  return job ? { job, abs: job.root } : fail("No finished scan yet. Call scan_folder first.");
}

const isResult = (v: unknown): v is ToolResult => typeof v === "object" && v !== null && "content" in v;

interface FolderHit {
  path: string;
  node: DirNode;
}

/** Find folders by name anywhere below `basePath`. Matches are not searched further. */
function searchFolders(base: DirNode, basePath: string, matches: (name: string) => boolean): FolderHit[] {
  const hits: FolderHit[] = [];
  const walk = (node: DirNode, nodePath: string) => {
    for (const c of node.children) {
      const cp = path.join(nodePath, c.name);
      if (matches(c.name)) hits.push({ path: cp, node: c });
      else walk(c, cp);
    }
  };
  walk(base, basePath);
  return hits;
}

function nameMatcher(patterns: string[]): (name: string) => boolean {
  const regs = patterns.map((p) => new RegExp("^" + p.replace(/[.+^${}()|[\]\\]/g, "\\$&").replace(/\*/g, ".*").replace(/\?/g, ".") + "$", "i"));
  return (name) => regs.some((r) => r.test(name));
}

async function withModified(hits: FolderHit[], olderThanDays?: number) {
  const now = Date.now();
  const rows = await Promise.all(
    hits.map(async (h) => {
      let mtime: number | undefined;
      try {
        mtime = (await fs.lstat(h.path)).mtimeMs;
      } catch {
        // Folder vanished since the scan.
      }
      return { ...h, mtime, days: mtime ? Math.floor((now - mtime) / 86400000) : undefined };
    })
  );
  return olderThanDays != null ? rows.filter((r) => r.days != null && r.days >= olderThanDays) : rows;
}

