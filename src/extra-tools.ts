async function hashFile(file: string, bytes?: number): Promise<string> {
  const hash = createHash("sha1");
  const stream = createReadStream(file, bytes ? { start: 0, end: bytes - 1 } : undefined);
  for await (const chunk of stream) hash.update(chunk as Buffer);
  return hash.digest("hex");
}

async function mapLimit<T, R>(items: T[], limit: number, deadline: number, fn: (i: T) => Promise<R>): Promise<Array<R | undefined>> {
  const out: Array<R | undefined> = new Array(items.length);
  let next = 0;
  await Promise.all(
    Array.from({ length: Math.min(limit, items.length) }, async () => {
      while (next < items.length && Date.now() < deadline) {
        const i = next++;
        try {
          out[i] = await fn(items[i]);
        } catch {
          out[i] = undefined;
        }
      }
    })
  );
  return out;
}

// ---- snapshots

const SNAPSHOT_DEPTH = 4;
const SNAPSHOT_MIN_BYTES = mb(10);

function snapshotDir(): string {
  return path.join(os.homedir(), ".diskscout", "snapshots");
}

function collectFolders(root: DirNode): Map<string, number> {
  const out = new Map<string, number>();
  const walk = (node: DirNode, rel: string, depth: number) => {
    for (const c of node.children) {
      if (c.size < SNAPSHOT_MIN_BYTES) continue;
      const r = rel ? rel + path.sep + c.name : c.name;
      out.set(IS_WIN ? r.toLowerCase() : r, c.size);
      if (depth < SNAPSHOT_DEPTH) walk(c, r, depth + 1);
    }
  };
  walk(root, "", 1);
  return out;
}

interface Snapshot {
  name: string;
  root: string;
  createdAt: string;
  totalBytes: number;
  files: number;
  folders: Array<[string, number]>;
}

const safeName = (s: string) => s.replace(/[^a-zA-Z0-9._-]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 80) || "snapshot";

const PS_BIN_INFO = `
$s = (New-Object -ComObject Shell.Application).NameSpace(0xA)
$items = @($s.Items())
$sum = [int64]0
foreach ($i in $items) { $sum += [int64]$i.Size }
"{0},{1}" -f $items.Count, $sum
`;

async function recycleBinInfo(): Promise<{ items: number; bytes: number }> {
  const out = await runPowerShell(PS_BIN_INFO, {}, 90000);
  const [items, bytes] = out.split(",").map(Number);
  if (!Number.isFinite(items) || !Number.isFinite(bytes)) throw new Error(`Unexpected output: ${out.slice(0, 100)}`);
  return { items, bytes };
}

